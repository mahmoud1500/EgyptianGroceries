/* Current language: 'ar' only when explicitly chosen, else 'en'. */
function lang() {
  try { return localStorage.getItem('ehf_lang') === 'ar' ? 'ar' : 'en'; }
  catch (e) { return 'en'; }
}

/* t(key, vars) — {var} interpolation; falls back to English, then the key. */
function t(key, vars) {
  const d = I18N[lang()] || {};
  let s = d[key] !== undefined ? d[key] : (I18N.en[key] !== undefined ? I18N.en[key] : key);
  if (vars) {
    s = String(s).replace(/\{(\w+)\}/g, function (m, k) {
      return (vars[k] !== undefined && vars[k] !== null) ? vars[k] : m;
    });
  }
  return s;
}

function setLang(l) {
  try { localStorage.setItem('ehf_lang', l === 'ar' ? 'ar' : 'en'); } catch (e) { /* ignore */ }
  applyLang();
}

/* Apply language to <html>, static data-i18n markup, toggle button, then re-render. */
function applyLang() {
  const l = lang();
  document.documentElement.lang = l;
  document.documentElement.dir = l === 'ar' ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    el.innerHTML = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
  });
  const btn = document.getElementById('lang-toggle');
  if (btn) {
    btn.textContent = l === 'ar' ? 'EN' : 'عربي';
    btn.setAttribute('aria-label', l === 'ar' ? 'Switch to English' : 'التبديل إلى العربية');
  }
  if (typeof render === 'function') render();
  if (typeof updateAuthArea === 'function') updateAuthArea();
}
